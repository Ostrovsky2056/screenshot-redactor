const { writeFileSync } = require("node:fs");
const { join } = require("node:path");
const { pairInputs } = require("../assets/chat-layout.js");

function dataset(seed, count) {
  let state = seed >>> 0;
  const random = () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 4294967296;
  };
  const range = (a, b) => a + (b - a) * random();
  const examples = [];
  // Generate balanced geometry and appearance samples across body lengths, themes and scales.
  for (let index = 0; index < count; index++) {
    const kind = index % 8;
    const label = Number(kind < 4);
    const frame = range(430, 1750);
    const side = random() < .5 ? "left" : "right";
    const size = range(25, 105);
    let edge = range(.009, .11) * frame;
    let gap = range(.12, .56) * size;
    let drop = (kind === 1 ? range(-.16, .12) : range(.30, .78)) * size;
    let avatarAspect = range(.89, 1.12);
    let avatarFlatness = kind === 2 ? range(.71, .93) : range(.15, .77);
    let bubbleFlatness = range(.74, .99);
    let bubbleWidth = (kind === 1 ? range(.65, 1.32) : range(1.25, 5)) * size;
    let bubbleFill = range(.72, 1);
    let hasText = random() > .09;

    if (kind === 4) {
      // A compact bubble beside a card or sticker can look almost like a flipped sender row.
      drop = range(-.55, .78) * size;
      edge = range(.05, .40) * frame;
      avatarFlatness = range(.78, .99);
      bubbleFlatness = range(.43, .83);
      bubbleWidth = range(.68, 1.9) * size;
      hasText = random() < .39;
    }
    if (kind === 5) {
      // Toolbar buttons or status icons tend to be flat and spaced differently.
      gap = range(.05, 1.16) * size;
      drop = range(-.43, .39) * size;
      avatarAspect = range(.72, 1.38);
      avatarFlatness = range(.80, 1);
      bubbleFlatness = range(.69, 1);
      bubbleWidth = range(.40, 2.25) * size;
      edge = range(.06, .36) * frame;
      hasText = random() < .57;
    }
    if (kind === 6) {
      // Images in nearby rows may be close horizontally while belonging to a different message.
      drop = (random() < .5 ? range(-.8, -.24) : range(.95, 1.65)) * size;
      gap = range(.38, 1.4) * size;
      avatarAspect = range(.78, 1.32);
      bubbleFlatness = range(.52, .91);
      bubbleFill = range(.54, .91);
    }
    if (kind === 7) {
      // Inner thumbnails and stickers share some texture with avatars away from the chat margins.
      edge = range(.16, .45) * frame;
      drop = range(-.30, .88) * size;
      avatarAspect = range(.70, 1.39);
      bubbleFlatness = range(.42, .89);
      bubbleFill = range(.47, .91);
      hasText = random() < .54;
    }

    const avatarW = size * avatarAspect;
    const x0 = side === "left" ? edge : frame - edge - avatarW;
    const y0 = range(30, 800);
    const avatar = { x0, y0, x1: x0 + avatarW, y1: y0 + size, flatness: avatarFlatness };
    const bx = side === "left" ? avatar.x1 + gap : avatar.x0 - gap - bubbleWidth;
    const bubble = {
      x0: bx, x1: bx + bubbleWidth, y0: y0 + drop, y1: y0 + drop + size * range(.62, 1.8),
      flatness: bubbleFlatness, fill: bubbleFill, hasText,
    };
    examples.push({ x: [1, ...pairInputs(avatar, bubble, side, frame)], label });
  }
  return examples;
}

const sigmoid = value => 1 / (1 + Math.exp(-value));
const dot = (features, weights) => features.reduce((sum, value, index) => sum + value * weights[index], 0);
const training = dataset(96581, 3200);
const weights = new Array(training[0].x.length).fill(0);
for (let epoch = 0; epoch < 1500; epoch++) {
  const gradient = new Array(weights.length).fill(0);
  for (const { x, label } of training) {
    const difference = sigmoid(dot(x, weights)) - label;
    for (let index = 0; index < weights.length; index++) gradient[index] += x[index] * difference;
  }
  for (let index = 0; index < weights.length; index++) {
    weights[index] -= .85 * (gradient[index] / training.length + (index === 0 ? 0 : .002 * weights[index]));
  }
}

const threshold = .65;
const rounded = weights.map(value => Number(value.toFixed(6)));
const source = `// Generated by scripts/train-chat-layout.cjs from synthetic chat layouts.
(function () {
  const weights = ${JSON.stringify(rounded)};

  function score(inputs) {
    let value = weights[0];
    for (let index = 0; index < inputs.length; index++) value += inputs[index] * weights[index + 1];
    return 1 / (1 + Math.exp(-value));
  }

  const model = { score, threshold: ${threshold} };
  if (typeof module !== "undefined") module.exports = model;
  else window.ChatLayoutModel = model;
})();
`;
writeFileSync(join(__dirname, "../assets/chat-layout-model.js"), source);

const heldOut = dataset(7193, 1200);
const selected = heldOut.filter(({ x }) => sigmoid(dot(x, weights)) >= threshold);
const truePositive = selected.filter(({ label }) => label).length;
const positives = heldOut.filter(({ label }) => label).length;
console.log(`Synthetic holdout: ${truePositive}/${positives} sender pairs selected; ${selected.length - truePositive} false positives.`);
